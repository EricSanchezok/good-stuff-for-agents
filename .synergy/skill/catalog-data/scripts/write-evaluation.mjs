#!/usr/bin/env node
import { existsSync, readFileSync } from 'node:fs'
import {
  assertCurrentEvaluationBinding,
  createEvaluationBinding,
  nowIso,
  parseYamlFile,
  stableStringify,
  writeTextAtomic,
  loadSkillsById,
} from './lib/catalog-lib.mjs'
import {
  evaluatePackV3, loadAnalysesByIds, loadRelationsByIds,
  recomputeContentDigest, validateProofRecord,
} from './lib/pack-v3-lib.mjs'
import { evaluationSchemaV2, validateAgainstSchema } from './lib/schema-validators.mjs'

const args = process.argv.slice(2)
const packIdIdx = args.indexOf('--pack-id')
const createBinding = args.includes('--create-binding')

let packId = null
if (packIdIdx !== -1 && args[packIdIdx + 1]) {
  packId = args[packIdIdx + 1]
}

if (createBinding) {
  if (!packId) throw new Error('--create-binding requires --pack-id <id>')
  const binding = createEvaluationBinding(packId)
  console.log(JSON.stringify(binding, null, 2))
  process.exit(0)
}

// Read envelope from stdin
const stdin = readFileSync(0, 'utf8')
const envelope = JSON.parse(stdin)
const { binding, draft } = assertEvaluationEnvelope(envelope)

// Use explicit pack-id if given, or derive from binding
if (packId && binding.pack_id !== packId) {
  throw new Error(`Binding pack_id ${binding.pack_id} does not match --pack-id ${packId}`)
}

const current = assertCurrentEvaluationBinding(binding)

if (existsSync(current.evaluationPath)) {
  const existing = JSON.parse(readFileSync(current.evaluationPath, 'utf8'))
  if (existing.evaluation_id === binding.evaluation_id) {
    throw new Error(`Evaluation binding has already been used: ${binding.evaluation_id}`)
  }
}

assertSemanticDraft(draft)

// Load the pack record
const pack = parseYamlFile(current.packPath)

// Load proof record from preflight-proof.json
const proofPath = current.evaluationPath.replace(/evaluation\.json$/, 'preflight-proof.json')
if (!existsSync(proofPath)) {
  throw new Error(`Proof file not found at ${proofPath}; pack must be written with proof before evaluation`)
}
const storedProofRecord = JSON.parse(readFileSync(proofPath, 'utf8'))
validateProofRecord(storedProofRecord, pack.pack_id)

// Verify draft proof_digest matches stored proof
const boundProofDigest = binding.proof_digest
if (draft.proof_digest && draft.proof_digest !== boundProofDigest) {
  throw new Error(`proof_digest in draft ${draft.proof_digest} does not match binding proof_digest ${boundProofDigest}`)
}
const effectiveProofDigest = draft.proof_digest ?? boundProofDigest ?? null

// Verify the stored proof content_digest matches the binding proof_digest
if (effectiveProofDigest && effectiveProofDigest !== storedProofRecord.content_digest) {
  throw new Error(`Stored proof content_digest ${storedProofRecord.content_digest} does not match evaluation proof_digest ${effectiveProofDigest}`)
}

// Load exact current evidence and recompute current content digest
const memberIds = (pack.members || []).map(m => m.skill_id)
const skillRecords = loadSkillsById(memberIds)
const skills = new Map(skillRecords.map(({ record: r }) => [r.canonical_skill_id, r]))
const analysisIds = pack.evidence?.analysis_ids ?? []
const analyses = loadAnalysesByIds(analysisIds)
const relationIds = pack.evidence?.relation_ids ?? []
const relations = loadRelationsByIds(relationIds)

// Recompute current content digest from exact canonical files
const currentContentDigest = recomputeContentDigest({ pack, analyses, relations, skills })

// Reject stale evidence: stored proof content_digest must match recomputed
if (storedProofRecord.content_digest !== currentContentDigest) {
  throw new Error(
    `Stale evidence: stored proof content_digest ${storedProofRecord.content_digest} ` +
    `does not match recomputed content digest ${currentContentDigest}. ` +
    `Proof must be regenerated by the pack writer only.`
  )
}

const evaluation = {
  schema_version: 2,
  evaluation_id: binding.evaluation_id,
  synthesis_session_id: draft.synthesis_session_id,
  evaluation_session_id: draft.evaluation_session_id,
  pack_id: binding.pack_id,
  metrics: draft.metrics ?? {},
  blockers: draft.blockers ?? [],
  checked_claim_ids: draft.checked_claim_ids ?? [],
  warnings: draft.warnings ?? [],
  proof_digest: storedProofRecord.content_digest,
  decision: null,
  created_by_run: draft.created_by_run ?? 'run_manual',
  created_at: draft.created_at ?? nowIso(),
}

// Run deterministic v3 evaluation
const evalResult = evaluatePackV3({
  evaluation,
  pack,
  proofDigest: storedProofRecord.content_digest,
  skills,
  relations,
  analyses,
})

// Persist canonical union of evaluator blockers + deterministic structural blockers
const allBlockers = dedupBlockers([
  ...(evaluation.blockers ?? []),
  ...(evalResult.blockers ?? []),
])
evaluation.blockers = allBlockers

// Persist deterministic warnings if returned
if (evalResult.warnings && evalResult.warnings.length > 0) {
  evaluation.warnings = dedupWarnings([
    ...(evaluation.warnings ?? []),
    ...evalResult.warnings,
  ])
}

// Compute decision from the canonical blocker+warnings set
evaluation.decision = evalResult.decision

const validation = validateAgainstSchema(evaluation, evaluationSchemaV2)
if (!validation.ok) {
  throw new Error(`Evaluation v2 schema validation failed: ${validation.errors.join('; ')}`)
}

// Re-verify binding is still current before write
assertCurrentEvaluationBinding(binding)
writeTextAtomic(current.evaluationPath, stableStringify(evaluation))

console.log(JSON.stringify(evaluation, null, 2))

function assertEvaluationEnvelope(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error('Evaluation input must be a controller envelope')
  const keys = Object.keys(value)
  if (keys.length !== 2 || !keys.includes('binding') || !keys.includes('draft')) {
    throw new Error('Evaluation input must contain only binding and draft')
  }
  return value
}

function assertSemanticDraft(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error('Evaluation draft must be an object')
  const controlledFields = new Set([
    'binding', 'created_at', 'destination', 'evaluation_id', 'expected_path',
    'kind', 'output_id', 'output_path', 'pack_hash', 'pack_id', 'pack_status',
    'pack_version', 'record_bucket', 'schema_version',
  ])
  for (const field of Object.keys(value)) {
    if (controlledFields.has(field)) throw new Error(`Evaluation draft must not include controller field ${field}`)
  }
  if (!value.synthesis_session_id) throw new Error('Evaluation draft needs synthesis_session_id')
  if (!value.evaluation_session_id) throw new Error('Evaluation draft needs evaluation_session_id')
  if (value.synthesis_session_id === value.evaluation_session_id) throw new Error('Synthesis and evaluation session IDs must differ')
  if (!value.metrics || typeof value.metrics !== 'object' || Array.isArray(value.metrics)) throw new Error('Evaluation draft is missing metrics')
  if (!Array.isArray(value.blockers)) throw new Error('Evaluation draft needs blockers array')
  if (!Array.isArray(value.checked_claim_ids)) throw new Error('Evaluation draft needs checked_claim_ids array')
  if (!Array.isArray(value.warnings)) throw new Error('Evaluation draft needs warnings array')
}

function dedupBlockers(blockers) {
  const seen = new Set()
  const result = []
  for (const b of blockers) {
    const key = JSON.stringify(sortDeep({ code: b.code, description: b.description, claim_id: b.claim_id }))
    if (seen.has(key)) continue
    seen.add(key)
    result.push(b)
  }
  return result
}

function dedupWarnings(warnings) {
  const seen = new Set()
  const result = []
  for (const w of warnings) {
    const key = JSON.stringify(sortDeep({ claim_id: w.claim_id, message: w.message }))
    if (seen.has(key)) continue
    seen.add(key)
    result.push(w)
  }
  return result
}

function sortDeep(value) {
  if (Array.isArray(value)) return value.map(sortDeep)
  if (value && typeof value === 'object') {
    const sorted = {}
    for (const key of Object.keys(value).sort()) sorted[key] = sortDeep(value[key])
    return sorted
  }
  return value
}
